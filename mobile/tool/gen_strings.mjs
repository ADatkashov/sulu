// Generates lib/core/strings.g.dart from web/src/i18n/{en,ru,kk}.ts (customer-facing keys only) so web and mobile share one set of texts.
// Run: node --experimental-strip-types tool/gen_strings.mjs
import { writeFileSync } from 'node:fs'
const load = async (l) => (await import(`../../web/src/i18n/${l}.ts`))[l]
const [en, ru, kk] = await Promise.all([load('en'), load('ru'), load('kk')])
const keep = (k) => !/^(b|a|p)\./.test(k)
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')
const block = (name, m) => `const Map<String, String> ${name} = {\n${Object.entries(m).filter(([k]) => keep(k)).map(([k, v]) => `  '${k}': '${esc(v)}',`).join('\n')}\n};\n`
writeFileSync('lib/core/strings.g.dart', `// GENERATED by tool/gen_strings.mjs — do not edit.\n${block('stringsEn', en)}\n${block('stringsRu', ru)}\n${block('stringsKk', kk)}`)
console.log('generated', Object.keys(en).filter(keep).length, 'keys')
